import type { EditorialAge, LyricAge, LyricReview, SheetFormat, SheetKind, SheetMusicSource, Song } from "../types";

const EDITORIAL_NOTE =
  "Предварительная редакторская оценка уместности текста, не официальная маркировка и не оценка голоса.";

const VOCAL_UNVERIFIED = {
  status: "unverified" as const,
  source: "Вокальные характеристики конкретной аранжировки не проверялись педагогом.",
};

function age(lyricAge: LyricAge, lyricReview: LyricReview = "preliminary"): EditorialAge {
  return { lyricAge, note: EDITORIAL_NOTE, lyricReview };
}

function song(
  entry: Omit<
    Song,
    "difficulty" | "rangeLow" | "rangeHigh" | "key" | "tessitura" | "verification" | "sheetMusic"
  > & { sheetMusic?: SheetMusicSource[] },
): Song {
  return {
    ...entry,
    difficulty: null,
    rangeLow: null,
    rangeHigh: null,
    key: null,
    tessitura: null,
    verification: VOCAL_UNVERIFIED,
    sheetMusic: entry.sheetMusic ?? [],
  };
}

const SHEET_CHECKED = "2026-10-31";

/** visualCheck: "pages-readable" только после просмотра страниц этой песни, не после открытия PDF. */
function sheet(
  source: Omit<SheetMusicSource, "checkedAt" | "sameAsRecommended" | "key" | "kind" | "format" | "registrationRequired"> & {
    key?: string | null;
    sameAsRecommended?: boolean;
    kind?: SheetKind;
    format?: SheetFormat;
    registrationRequired?: boolean;
    collectionPdfPage?: number;
    collectionPrintPage?: number | string;
    visualCheck?: "pages-readable";
  },
): SheetMusicSource {
  return {
    checkedAt: SHEET_CHECKED,
    sameAsRecommended: source.sameAsRecommended ?? false,
    key: source.key ?? null,
    kind: source.kind ?? "vocal",
    format: source.format ?? "single",
    registrationRequired: source.registrationRequired ?? false,
    url: source.url,
    publisher: source.publisher,
    versionNote: source.versionNote,
    scoring: source.scoring,
    access: source.access,
    ...(source.collectionPdfPage != null ? { collectionPdfPage: source.collectionPdfPage } : {}),
    ...(source.collectionPrintPage != null ? { collectionPrintPage: source.collectionPrintPage } : {}),
    ...(source.visualCheck ? { visualCheck: source.visualCheck } : {}),
  };
}

